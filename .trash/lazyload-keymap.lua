--------------------------------------------------------------------------------
-- render-markdown.nvim 快捷键懒加载
--------------------------------------------------------------------------------

local loaded = false

vim.keymap.set("n", "<leader>md", function()

    ------------------------------------------------------------------------
    -- 1. 防止重复加载
    ------------------------------------------------------------------------

    if loaded then
        require("render-markdown").toggle()
        return
    end

    ------------------------------------------------------------------------
    -- 2. 安装插件
    ------------------------------------------------------------------------

    vim.pack.add({
        "https://github.com/nvim-treesitter/nvim-treesitter",
        "https://github.com/nvim-mini/mini.nvim",
        "https://github.com/MeanderingProgrammer/render-markdown.nvim",
    })

    ------------------------------------------------------------------------
    -- 3. 初始化插件
    ------------------------------------------------------------------------

    require("render-markdown").setup({
        file_types = { "markdown" },
        enabled = true,
        render_modes = { "n", "c", "t" },
        debounce = 100,
        max_file_size = 10.0,
    })

    ------------------------------------------------------------------------
    -- 4. 标记加载完成
    ------------------------------------------------------------------------

    loaded = true

    ------------------------------------------------------------------------
    -- 5. 执行切换
    ------------------------------------------------------------------------

    require("render-markdown").toggle()

end, {
    noremap = true,
    silent = true,
    desc = "加载/切换 Markdown 渲染",
})
